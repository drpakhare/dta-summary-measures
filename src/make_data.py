"""Illustrative DTA dataset for the session: CRP for serious bacterial infection (SBI)
in febrile infants aged 90 days or less. Five invented studies at different CRP cut-offs.

Deterministic. Writes data/crp-dta.csv, data/crp-dta.json and widgets/crp-data.js.
All numbers are constructed for teaching and do not describe any real study.

Underlying model (binormal on log CRP, mg/L):
  no SBI : log CRP ~ N(ln 7,  1.00)
  SBI    : log CRP ~ N(ln 45, 1.10)
Each study gets a small shift in the SBI mean (spectrum) so points scatter round the curve.
"""
import json, math, pathlib
from statistics import NormalDist

ROOT = pathlib.Path(__file__).resolve().parents[1]
Z = NormalDist()
MU0, SD0 = math.log(7), 1.00
MU1, SD1 = math.log(45), 1.10

def sn(t, shift=0.0): return 1 - Z.cdf((math.log(t) - (MU1 + shift)) / SD1)
def sp(t): return Z.cdf((math.log(t) - MU0) / SD0)

# id, label, setting, country-free description, N, n with SBI, threshold, SBI-mean shift
STUDIES = [
    ("A", "Study A", "Paediatric emergency department, single centre", 640, 77, 20, 0.15),
    ("B", "Study B", "Three paediatric emergency departments", 1100, 99, 20, -0.20),
    ("C", "Study C", "Neonatal unit, infants up to 28 days", 420, 76, 40, 0.20),
    ("D", "Study D", "Paediatric emergency department, two centres", 760, 84, 40, -0.15),
    ("E", "Study E", "General paediatric admissions", 380, 57, 80, 0.10),
]

rows = []
for sid, label, setting, n, d, t, shift in STUDIES:
    nd = n - d
    tp = round(d * sn(t, shift)); fn = d - tp
    tn = round(nd * sp(t)); fp = nd - tn
    rows.append(dict(id=sid, study=label, setting=setting, threshold=t, N=n,
                     TP=tp, FP=fp, FN=fn, TN=tn))

# Multiple thresholds reported by Study E (for the extraction exercise)
e = next(r for r in rows if r["id"] == "E")
e_multi = []
for t in (20, 40, 80):
    tp = round(57 * sn(t, 0.10)); tn = round(323 * sp(t))
    e_multi.append(dict(threshold=t, TP=tp, FP=323 - tn, FN=57 - tp, TN=tn))

# Underlying curve for plotting (fpr, tpr) at many thresholds
curve = [dict(t=round(math.exp(x / 20), 3), fpr=1 - sp(math.exp(x / 20)), tpr=sn(math.exp(x / 20)))
         for x in range(-40, 161)]
a = (MU1 - MU0) / SD1; b = SD0 / SD1
auc = Z.cdf(a / math.sqrt(1 + b * b))

out = dict(model=dict(mu0=MU0, sd0=SD0, mu1=MU1, sd1=SD1, auc=auc),
           studies=rows, studyE_multi=e_multi)
(ROOT / "data").mkdir(exist_ok=True)
(ROOT / "data/crp-dta.json").write_text(json.dumps(out, indent=1))
with open(ROOT / "data/crp-dta.csv", "w") as f:
    f.write("Study,Setting,Threshold_mg_per_L,TP,FP,FN,TN\n")
    for r in rows:
        f.write(f'{r["study"]},"{r["setting"]}",{r["threshold"]},{r["TP"]},{r["FP"]},{r["FN"]},{r["TN"]}\n')
(ROOT / "widgets/crp-data.js").write_text(
    "// Illustrative CRP DTA dataset, generated by src/make_data.py. Constructed for teaching.\n"
    "window.CRP = " + json.dumps(out) + ";\n")

for r in rows:
    tp, fp, fn, tn = r["TP"], r["FP"], r["FN"], r["TN"]
    S, P = tp / (tp + fn), tn / (tn + fp)
    print(r["id"], r["threshold"], r["N"], tp, fp, fn, tn,
          f"Sn {S:.3f} Sp {P:.3f} PPV {tp/(tp+fp):.3f} NPV {tn/(tn+fn):.3f} "
          f"LR+ {S/(1-P):.2f} LR- {(1-S)/P:.3f} DOR {tp*tn/(fp*fn):.1f} prev {(tp+fn)/r['N']:.3f}")
print("E multi", e_multi)
print("AUC", round(auc, 3))
for t in (10, 20, 40, 80):
    print(t, round(sn(t), 3), round(sp(t), 3))
